"""
Day 05 练习 —— 字典
日期：2026-11-21（计划表 W1 第 5 天）

为什么字典最重要：
后面 4 个月，你 90% 的数据都是字典——API 返回是字典、大模型返回是字典、
配置文件是字典、RAG 的元数据是字典。列表装的是"一堆东西"，
字典装的是"有名字的东西"，而真实世界的数据几乎都有名字。

新知识速览
------------------------------------------------------------------
① 创建与访问
    person = {"name": "张三", "age": 23}
    person["name"]        # 张三
    person["city"]        # ❌ KeyError，键不存在会直接报错

② get() 比 [] 安全（重点）
    person.get("city")        # None
    person.get("city", "未知") # "未知"   ← 第二个参数是默认值

    真实项目里读配置、读接口字段，永远用 .get()，不要用 []。

③ 增、改、删
    person["job"] = "待业"     # 键不存在就是新增
    person["age"] = 24        # 键存在就是修改
    del person["age"]         # 删除
    person.pop("age")         # 删除并拿到值

④ 三种遍历
    for k in d:               # 遍历键
    for v in d.values():      # 遍历值
    for k, v in d.items():    # 遍历键值对（最常用）

⑤ 排序字典（必考）
    sorted(d.items(), key=lambda kv: kv[1], reverse=True)
    # kv 是 (键, 值) 元组，kv[1] 是按值排；按值降序

⑥ 合并
    a.update(b)     # 把 b 并进 a，键冲突时 b 覆盖 a
    c = a | b       # Python 3.9+ 返回新字典

⑦ setdefault（分组神器）
    groups.setdefault(key, []).append(x)
    # key 不存在就先用 [] 占位，再 append

⑧ JSON 与字典
    import json
    json.dumps(d)          # 字典 → 字符串（发请求时用）
    json.loads(s)          # 字符串 → 字典（收响应时用）
------------------------------------------------------------------
"""
